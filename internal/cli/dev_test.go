func TestDev_DockerPreflight(t *testing.T) {
	boom := errors.New("boom")
	cases := []struct {
		name string
		d    *fakeDocker
		msg  string
	}{
		{"not installed", &fakeDocker{lookErr: boom}, "Docker isn't installed"},
		{"not running", &fakeDocker{versionErr: boom}, "Docker isn't running"},
		{"no compose v2", &fakeDocker{composeErr: boom}, "Docker Compose v2"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir, path := newProject(t, phoenix, nil)
			code, _, stderr := run(tc.d, "-f", path, "dev")
			if code != 1 {
				t.Errorf("exit = %d, want 1", code)
			}
			if !strings.Contains(stderr, tc.msg) {
				t.Errorf("stderr = %q, want %q", stderr, tc.msg)
			}
			if len(tc.d.runs) != 0 {
				t.Errorf("compose ran: %q", tc.d.runs)
			}
			if _, err := os.Stat(filepath.Join(dir, ".houston")); !os.IsNotExist(err) {
				t.Errorf(".houston was created")
			}
		})
	}
}

func TestDev_WarnsAboutVariables(t *testing.T) {
	cases := []struct {
		name    string
		env     *string // nil → no .env
		shell   map[string]string
		listed  []string
		missing bool // expects the ".env is missing" wording
	}{
		{"no .env", nil, nil, []string{"POSTGRES_PASSWORD", "SECRET_KEY_BASE"}, true},
		{"blank and absent", ptr("SECRET_KEY_BASE=\nOTHER=hunter2\n"), nil, []string{"POSTGRES_PASSWORD", "SECRET_KEY_BASE"}, false},
		{"set in the shell", ptr("SECRET_KEY_BASE=abc\n"), map[string]string{"POSTGRES_PASSWORD": "from-shell"}, nil, false},
		{"all set", ptr("POSTGRES_PASSWORD=p\nSECRET_KEY_BASE=hunter2\n"), nil, nil, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			for k, v := range tc.shell {
				t.Setenv(k, v)
			}
			files := map[string]string{}
			if tc.env != nil {
				files[".env"] = *tc.env
			}
			_, path := newProject(t, phoenix, files)
			d := &fakeDocker{}

			code, _, stderr := run(d, "-f", path, "dev")

			if code != 0 || len(d.runs) != 1 {
				t.Fatalf("exit = %d, runs = %d; warnings must not stop dev (stderr: %s)", code, len(d.runs), stderr)
			}
			for _, name := range tc.listed {
				if !strings.Contains(stderr, name) {
					t.Errorf("stderr doesn't list %s: %s", name, stderr)
				}
			}
			if tc.listed == nil && withoutUpLine(stderr) != "" {
				t.Errorf("unexpected warning: %s", stderr)
			}
			for _, never := range []string{"DB_HOST", "LOG_LEVEL", "hunter2", "from-shell"} {
				if strings.Contains(stderr, never) {
					t.Errorf("stderr mentions %q: %s", never, stderr)
				}
			}
			if tc.missing && !strings.Contains(stderr, "no .env") {
				t.Errorf("stderr doesn't say .env is missing: %s", stderr)
			}
		})
	}
}

