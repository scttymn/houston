func TestDev_GeneratedFile(t *testing.T) {
	env := map[string]string{".env": "POSTGRES_PASSWORD=x\nSECRET_KEY_BASE=y\n"}

	t.Run("replaces a stale file and reruns identically", func(t *testing.T) {
		files := map[string]string{".houston/compose.dev.yml": "stale\n"}
		for k, v := range env {
			files[k] = v
		}
		dir, path := newProject(t, phoenix, files)
		generated := filepath.Join(dir, ".houston", "compose.dev.yml")

		run(&fakeDocker{}, "-f", path, "dev")
		first, _ := os.ReadFile(generated)
		run(&fakeDocker{}, "-f", path, "dev")
		second, _ := os.ReadFile(generated)

		if string(first) != wantOverride || string(second) != wantOverride {
			t.Errorf("generated =\n%s\nthen\n%s\nwant\n%s", first, second, wantOverride)
		}
		var names []string
		entries, _ := os.ReadDir(filepath.Join(dir, ".houston"))
		for _, e := range entries {
			names = append(names, e.Name())
		}
		if !reflect.DeepEqual(names, []string{".gitignore", "compose.dev.yml"}) {
			t.Errorf(".houston holds %v, want .gitignore and compose.dev.yml (temp files left behind?)", names)
		}
		if ignore, _ := os.ReadFile(filepath.Join(dir, ".houston", ".gitignore")); string(ignore) != "*\n" {
			t.Errorf(".houston/.gitignore = %q, want \"*\\n\" so the folder is never committed", ignore)
		}
	})

	t.Run(".houston is a file", func(t *testing.T) {
		files := map[string]string{".houston": "not a dir\n"}
		for k, v := range env {
			files[k] = v
		}
		_, path := newProject(t, phoenix, files)
		d := &fakeDocker{}

		code, _, stderr := run(d, "-f", path, "dev")

		if code != 1 {
			t.Errorf("exit = %d, want 1", code)
		}
		if !strings.Contains(stderr, "can't write .houston/compose.dev.yml") {
			t.Errorf("stderr = %s", stderr)
		}
		if len(d.runs) != 0 {
			t.Errorf("compose ran: %q", d.runs)
		}
	})
}

func TestCLI_FileFlagAndUsageErrors(t *testing.T) {
	t.Run("relative -f", func(t *testing.T) {
		root := t.TempDir()
		sub := filepath.Join(root, "sub")
		must(t, os.MkdirAll(sub, 0o755))
		must(t, os.WriteFile(filepath.Join(sub, "compose.yml"), []byte(phoenix), 0o644))
		must(t, os.WriteFile(filepath.Join(sub, ".env"), []byte("POSTGRES_PASSWORD=x\nSECRET_KEY_BASE=y\n"), 0o644))
		t.Chdir(root)
		d := &fakeDocker{}

		code, _, stderr := run(d, "-f", "sub/compose.yml", "dev")

		if code != 0 {
			t.Fatalf("exit = %d (stderr: %s)", code, stderr)
		}
		wantDir, _ := filepath.EvalSymlinks(sub)
		gotDir, _ := filepath.EvalSymlinks(d.runDirs[0])
		if gotDir != wantDir {
			t.Errorf("project dir = %q, want %q", d.runDirs[0], sub)
		}
	})
	// Like docker compose: -f/--file goes before the command (houston -f x dev).
	t.Run("file flag after the command", func(t *testing.T) {
		_, path := newProject(t, phoenix, map[string]string{".env": "POSTGRES_PASSWORD=x\nSECRET_KEY_BASE=y\n"})
		for _, args := range [][]string{{"dev", "-f", path}, {"test", "--file", path}} {
			d := &fakeDocker{}
			code, _, stderr := run(d, args...)
			if code != 2 || d.calls() != 0 || !strings.Contains(stderr, "unknown") {
				t.Errorf("%q: exit = %d, calls = %d, stderr = %q; want a usage error", args, code, d.calls(), stderr)
			}
		}
	})
	for _, args := range [][]string{{"dev", "--server"}, {"dev", "--production"}, {"dev", "--nope"}, {"bogus"}} {
		t.Run(strings.Join(args, " "), func(t *testing.T) {
			d := &fakeDocker{}
			code, _, stderr := run(d, args...)
			if code != 2 {
				t.Errorf("exit = %d, want 2 (stderr: %s)", code, stderr)
			}
			if d.calls() != 0 {
				t.Errorf("docker was called")
			}
		})
	}
}

func ptr(s string) *string { return &s }

// withoutUpLine drops houston dev's "… is up at http://…" line, for tests
// about everything else it prints.
func withoutUpLine(stderr string) string {
	var kept []string
	for _, line := range strings.SplitAfter(stderr, "\n") {
		if !strings.Contains(line, " is up at http://") {
			kept = append(kept, line)
		}
	}
	return strings.Join(kept, "")
}
