const wantOverride = "# Generated by houston. Do not edit.\nservices:\n  app:\n    build:\n      target: dev\n    ports: !reset []\n    networks:\n      default: {}\n      houston-dev:\n        aliases:\n          - phoenixapp.localhost\n  db:\n    ports: !reset []\nnetworks:\n  houston-dev:\n    external: true\n"

// newProject writes compose.yml (and optional extra files) into a temp dir and
// returns the dir and the compose file's absolute path.
func newProject(t *testing.T, compose string, files map[string]string) (string, string) {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "compose.yml")
	must(t, os.WriteFile(path, []byte(compose), 0o644))
	for name, content := range files {
		must(t, os.MkdirAll(filepath.Dir(filepath.Join(dir, name)), 0o755))
		must(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644))
	}
	return dir, path
}

func run(d *fakeDocker, args ...string) (code int, stdout, stderr string) {
	return runWithInput(d, "", args...)
}

func runWithInput(d *fakeDocker, input string, args ...string) (code int, stdout, stderr string) {
	var out, errOut bytes.Buffer
	code = Main(args, strings.NewReader(input), &out, &errOut, d)
	return code, out.String(), errOut.String()
}

func must(t *testing.T, err error) {
	t.Helper()
	if err != nil {
		t.Fatal(err)
	}
}

func upArgs(dir, path string) []string {
	return []string{"compose", "-p", "phoenixapp", "--project-directory", dir, "-f", path, "-f", filepath.Join(dir, ".houston", "compose.dev.yml"), "up", "--build"}
}

func TestDev_RunsComposeWithOverride(t *testing.T) {
	// A stray COMPOSE_PROJECT_NAME would rename the containers; -p pins the name.
	dir, path := newProject(t, phoenix, map[string]string{".env": "POSTGRES_PASSWORD=x\nSECRET_KEY_BASE=y\nCOMPOSE_PROJECT_NAME=other\n"})
	t.Setenv("COMPOSE_PROJECT_NAME", "other")
	var atRun string
	d := &fakeDocker{runExit: 3, onRun: func() {
		b, _ := os.ReadFile(filepath.Join(dir, ".houston", "compose.dev.yml"))
		atRun = string(b)
	}}

	code, _, stderr := run(d, "-f", path, "dev")

	if code != 3 {
		t.Errorf("exit = %d, want compose's 3 (stderr: %s)", code, stderr)
	}
	if len(d.runs) != 1 || !reflect.DeepEqual(d.runs[0], upArgs(dir, path)) {
		t.Fatalf("runs = %q\nwant %q", d.runs, upArgs(dir, path))
	}
	if d.runDirs[0] != dir {
		t.Errorf("run dir = %q, want %q", d.runDirs[0], dir)
	}
	if atRun != wantOverride {
		t.Errorf("override when compose ran =\n%s\nwant\n%s", atRun, wantOverride)
	}
	if stderr != "houston: phoenixapp is up at http://phoenixapp.localhost\n" {
		t.Errorf("unexpected stderr: %s", stderr)
	}
}

