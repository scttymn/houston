package variant

import (
	"testing"

	"github.com/scttymn/houston/internal/project"
)

func TestDevOverride_ForcesDevTarget(t *testing.T) {
	p, err := project.Load("../project/testdata/phoenixapp.compose.yml")
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by houston. Do not edit.\n" +
		"services:\n" +
		"  app:\n" +
		"    build:\n" +
		"      target: dev\n"
	first := string(DevOverride(p, Route{KeepPorts: true}))
	if first != want {
		t.Errorf("DevOverride =\n%s\nwant\n%s", first, want)
	}
	if second := string(DevOverride(p, Route{KeepPorts: true})); second != first {
		t.Errorf("second call differs:\n%s", second)
	}
}

func TestDevOverride_UsesAppServiceName(t *testing.T) {
	p := &project.Project{Name: "demo", AppService: "web"}
	want := "# Generated by houston. Do not edit.\n" +
		"services:\n" +
		"  web:\n" +
		"    build:\n" +
		"      target: dev\n"
	if got := string(DevOverride(p, Route{KeepPorts: true})); got != want {
		t.Errorf("DevOverride =\n%s\nwant\n%s", got, want)
	}
}

// houston dev at <name>.localhost (docs/plans/dev-localhost.md, row 2):
// no service publishes a host port, and the app joins houston-dev, where the
// proxy reaches it by its alias.
func TestDevOverrideRoutesByName(t *testing.T) {
	p, err := project.Load("../project/testdata/phoenixapp.compose.yml")
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by houston. Do not edit.\n" +
		"services:\n" +
		"  app:\n" +
		"    build:\n" +
		"      target: dev\n" +
		"    ports: !reset []\n" +
		"    networks:\n" +
		"      default: {}\n" +
		"      houston-dev:\n" +
		"        aliases:\n" +
		"          - phoenixapp-feature1.houston\n" +
		"  cache:\n" +
		"    ports: !reset []\n" +
		"  db:\n" +
		"    ports: !reset []\n" +
		"networks:\n" +
		"  houston-dev:\n" +
		"    external: true\n"
	if got := string(DevOverride(p, Route{Alias: "phoenixapp-feature1.houston"})); got != want {
		t.Errorf("DevOverride =\n%s\nwant\n%s", got, want)
	}
}
